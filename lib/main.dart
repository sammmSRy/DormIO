import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';

import 'dev/db_smoke_test_page.dart';
import 'firebase_options.dart'; // generated by:  flutterfire configure

/// Set to true to test against the LOCAL emulators instead of the real project:
///   firebase emulators:start --only firestore,auth
const bool kUseEmulator = false;

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  if (kUseEmulator) {
    // Android emulator reaches your PC through 10.0.2.2
    final host = (!kIsWeb && defaultTargetPlatform == TargetPlatform.android)
        ? '10.0.2.2'
        : 'localhost';
    FirebaseFirestore.instance.useFirestoreEmulator(host, 8080);
    await FirebaseAuth.instance.useAuthEmulator(host, 9099);
  }
  runApp(const DormioApp());
}

class DormioApp extends StatelessWidget {
  const DormioApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'DormIO',
      debugShowCheckedModeBanner: false,
      theme: ThemeData(
        colorSchemeSeed: const Color(0xFF5F5F42), // olive from the DormIO UI
        useMaterial3: true,
      ),
      // Member 1: replace this with the real Welcome / Sign In screen.
      home: const DbSmokeTestPage(),
    );
  }
}
